/***************************************************************************
 * ai_survey.h — умный геолог (Р7, шаг 13, часть 4а; схема Владыки 27.10.2026, PLAN.md §6; §7 п. 104).
 *
 * Геолог видит ресурсы в квадрате 3×3 вокруг себя (cVehicle::doSurvey — при каждом шаге). Прежняя разведка
 * шла к ближайшей неразведанной клетке с ничьей «на запад» (обход по столбцам и строгое «<»), а геолог-амфибия
 * уходил в море — база с морем на западе оставалась без шахт (п. 104).
 *
 * Схема Владыки (решения простые и пишутся в журнал — событие «survey»):
 *  1. Кольца вокруг центра базы полосой шириной 3: геолог идёт по средней линии кольца (Чебышёв 3, 6, 9, …) к
 *     клетке, у которой в 3×3 есть неразведанная клетка под шахту (суша); кольцо за кольцом. Ничья — симметрично:
 *     ближе к геологу, затем меньший угол от направления «центр базы → центр карты» (у двух баз, повёрнутых на
 *     180°, выбор повёрнут так же), а не порядком обхода.
 *  2. Нашёл ресурс — доразведать жилу целиком (неразведанные соседи разведанных клеток с ресурсом), потом снова
 *     кольца.
 *  3. К разведанной базе врага (его здания из памяти) не ближе kEnemyGap, к предполагаемой (точка напротив нашей
 *     базы, пока врага не видели) — не ближе kGuessGap: там ракетомёты и скауты.
 *  4. Под угрозой (зона «дальность + ход» врага): успевает за ход в безопасную клетку — уходит (вода лучше: скаут
 *     по воде втрое медленнее — схема, п. 5); не успевает — последние ходы тратит на разведку нового рядом, а не
 *     бежит по разведанному.
 *  6. Бомбардировщики (ai_air): скаут врага у наших геологов и стройщиков — ценнее (охота на скаутов у геологов).
 * Р24 (п. 164, R21 §11): у центра карты точка напротив оказывалась в 19–23 клетках от своей базы — «враг совсем рядом»
 * отдавал геолога прежней разведке, а та обрезала каждый путь, кончавшийся у точки напротив: геолог стоял всю партию (Delta
 * с высадкой у центра; Donuts — у игрока 0 точка напротив в 23 клетках, геолог стоял до 86-го хода). Теперь такая
 * точка напротив на большой карте — не догадка о враге (кольца вокруг базы, как везде; на малой карте, сторона меньше
 * 3 × kCloseEnemy, враг и так близко — догадка остаётся), а прежняя разведка (кольца пройдены) обходит клетки у базы врага
 * при выборе цели, если враг не «совсем рядом» (рядом — прежнее поведение: на Donuts оно выигрывает ранней армией).
 * Выключатели — MAXR_SURVEY_GUESS=0, MAXR_SURVEY_SKIP=0.
 * Второй геолог при армии в походе (П8) — как прежде (ai_rule_brain). Всё детерминированно: обход по клеткам и id.
 * Опыт «вариант против варианта»: MAXR_SURVEY=0 — прежняя разведка.
 ***************************************************************************/

#ifndef ai_headless_ai_surveyH
#define ai_headless_ai_surveyH

#include "utility/position.h"

#include <nlohmann/json.hpp>

#include <set>
#include <string>
#include <vector>

class cMapView;
class cModel;
class cPlayer;
class cVehicle;

namespace ai
{

class cWorldModel;

class cSurvey
{
public:
	// раз в ход (до микро): центр базы, зона врага, жилы, счётчики
	void update (const cModel& model, const cPlayer& player, const cWorldModel& world, const cPosition& baseCenter, int turn);
	// включена ли новая разведка (MAXR_SURVEY=0 — прежняя)
	bool enabled() const { return enabled_; }
	// путь геолога v в этот ход (обрезан до хода не здесь — движок идёт по пути) и причина; пусто — стоять
	std::vector<cPosition> pathFor (const cModel& model, const cPlayer& player, const cMapView& view, const cWorldModel& world,
		const cVehicle& v, std::string& why);
	// клетка — у базы врага (известной или предполагаемой): геологу и стройщикам туда не идти
	bool nearEnemy (const cPosition& p) const;
	// Р24 (п. 164): прежняя разведка обходит клетки у базы врага при выборе цели, а не стоит, когда ближайшая цель у врага
	// (MAXR_SURVEY_SKIP=0 — как до Р24: путь к такой цели обрезается, геолог стоит). Только когда враг не «совсем рядом»: на
	// тесной карте стоящий геолог оставлял металл армии (Donuts — см. ai_survey.cpp, update)
	bool skipNearEnemy() const { return skipNear_ && !closeEnemy_; }

	std::vector<nlohmann::json> takeEvents();

	struct sCounts
	{
		int explored20 = 0; // разведанных клеток в радиусе 20 от центра базы
		int explored = 0;   // разведанных клеток на карте
		int mines = 0;      // своих шахт
		int surveyors = 0;
		int lost = 0;       // геологов потеряно за партию
		int flights = 0;    // уходов из-под угрозы за ход (за партию)
		int lastStand = 0;  // «не успевает — разведка рядом» (за партию)
		int veins = 0;      // целей «жила» (за партию)
	};
	const sCounts& counts() const { return counts_; }

private:
	void event (const char* what, nlohmann::json extra);
	// ключ «ничьей — симметрично»: угол клетки от направления «центр базы → центр карты», 0…359
	int angleKey (const cPosition& c) const;
	bool mineCell (const cModel& model, const cPosition& c) const; // суша, где может стоять шахта

	bool enabled_ = true;
	int turn_ = 0;
	int W_ = 0;
	int H_ = 0;
	cPosition center_ {-1, -1};
	double dirAngle_ = 0.0;               // направление «центр базы → центр карты», радианы
	std::vector<cPosition> enemyBuildings_;
	cPosition guess_ {-1, -1};            // предполагаемая база врага (точка напротив), пока его не видели
	// Р24 (п. 164): точка напротив ближе kCloseEnemy к своей базе на большой карте — догадка не о враге (мы у центра карты),
	// её нет (MAXR_SURVEY_GUESS=0 — как до Р24); в журнал — один раз за партию
	bool guessCheck_ = true;
	bool guessDropNoted_ = false;
	bool skipNear_ = true;
	bool closeEnemy_ = false; // база врага (здания или точка напротив) ближе kCloseEnemy к центру базы — прежняя разведка
	std::vector<cPosition> veinTargets_;  // неразведанные соседи разведанных ресурсных клеток у базы
	std::vector<cPosition> taken_;        // цели других геологов в этот ход
	std::set<unsigned int> known_;        // свои геологи (гибель — в журнал)
	std::vector<std::pair<unsigned int, cPosition>> lastPos_;
	// Р17 (п. 140): «где может быть» враг — вооружённая наземная машина из памяти (бомбардировщик облетит любую зону): клетка, радиус = дальность +
	// ход × (возраст памяти + 1) (не больше трёх ходов): за туманом враг не стоит на месте (r17base: геологов убивают танки 150,
	// бомбардировщики 46, ракеты 29, артиллерия 25 из 288 — скаутов среди убийц нет; геолог шёл к клетке «вне досягаемости» врага,
	// виденного 3–5 ходов назад). Геолог в такой зоне свежего врага (виден ≤ 2 ходов назад) уходит к центру базы, цели в ней не берёт
	struct sRoam
	{
		cPosition pos;
		int r = 0;
		bool fresh = false;
	};
	std::vector<sRoam> roam_;
	bool roaming (const cPosition& p, bool freshOnly) const;
	sCounts counts_;
	std::vector<nlohmann::json> events_;
};

} // namespace ai

#endif // ai_headless_ai_surveyH
